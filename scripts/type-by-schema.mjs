#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';

import { runtimeBy } from '@ton-community/tlb-runtime';
import '@ton-community/tlb-runtime/type-export.js';

const paths = process.argv.slice(2);
if (!paths.length) {
    process.stderr.write('Usage: scripts/type-by-schema.mjs <schema.tlb> [more.tlb ...]\n');
    process.exitCode = 1;
}

for (const path of paths) {
    try {
        if (!path.endsWith('.tlb')) throw new Error('Expected a .tlb file');
        const runtime = runtimeBy(readFileSync(path, 'utf8'), { autoText: false });
        const types = runtime.toTypeScript({ rootType: runtime.lastTypeName });
        const data = `/** generated by scripts/type-by-schema.mjs */\n\n${types}`;
        writeFileSync(path.replace(/\.tlb$/, '.d.ts'), data);
    } catch (error) {
        process.stderr.write(`${path}: ${error.message}\n`);
        process.exitCode = 1;
    }
}
